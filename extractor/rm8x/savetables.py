"""scenes/save_tables.txt: the two tables the port's save code needs that used to be compiled into the app (port/app/save_big5.inc,
save_terra_order.inc, generated by scripts/export_save_big5.py and export_save_terra_order.py from the game data).  Here they are produced at
extraction time, in plain text, and for the edition that is installed (Big5 for the old install, GBK for the Steam release).

Format (UTF-8, one record per line):
  encoding <cp950|gbk>
  code <unicode hex> <native code hex>      for every non-ASCII character of the stock names (scenes/stocks.txt): the 2-byte code in that encoding
  terra <map dir> <wonders> <n> <i0> <i1> ... the order of the original's Terra array as indices into the port's plot list (n entries)
"""
import re


def parse_terra_inc(text):
    """The generated C++ include of export_save_terra_order.py -> [(dir, wonders, order list)]."""
    arrays = {m.group(1): [int(v) for v in m.group(2).split(',') if v.strip()]
              for m in re.finditer(r'static const int RM8TO_(\w+)\[\] = \{([^}]*)\};', text)}
    out = []
    for m in re.finditer(r'\{"(\w+)", RM8TO_(\w+), (\d+), (\d+)\}', text):
        d, key, n, wonders = m.group(1), m.group(2), int(m.group(3)), int(m.group(4))
        order = arrays[key]
        if len(order) != n:
            raise ValueError('terra order of %s has %d entries, table says %d' % (d, len(order), n))
        out.append((d, wonders, order))
    if not out:
        raise ValueError('no terra tables found')
    return out


def native_codes(stocks_txt, enc):
    """{unicode: 2-byte native code} of the non-ASCII characters of the stock names (7th tab-separated field of 'stock' lines)."""
    chars = set()
    for line in open(stocks_txt, encoding='utf-8'):
        t = line.rstrip('\n').split('\t')
        if len(t) >= 7 and t[0] == 'stock':
            chars.update(t[6])
    out = {}
    for c in sorted(chars):
        if ord(c) < 128:
            continue
        b = c.encode(enc)
        if len(b) != 2:
            raise ValueError('%r does not encode to 2 bytes in %s' % (c, enc))
        out[ord(c)] = b[0] << 8 | b[1]
    return out


def write_save_tables(path, enc, codes, terra):
    lines = ['# generated by rm8_extract: tables for the original save format (docs/assets_legal.md); see rm8x/savetables.py', 'encoding %s' % enc]
    lines += ['code %04x %04x' % kv for kv in sorted(codes.items())]
    lines += ['terra %s %d %d %s' % (d, w, len(o), ' '.join(str(v) for v in o)) for d, w, o in terra]
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')
