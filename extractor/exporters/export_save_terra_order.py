"""Writes port/app/save_terra_order.inc: for every map, the order of the Terra array of the ORIGINAL (TerraMgr +0x10, the order of the plots in the
record's terra section) as indices into the port's plot list (scenes/<map>/scene.txt "terra" lines = placement anchors in tile order).
[H, confirmed on the three sample maps 1, 3, 10 of record_m01 / 01 / 03 / 08: the plot types of the 48 / 39 / 41 records agree] The original creates a Terra
object when the cell scan (FUN_004f07d0, tile order) first meets a tile carrying the plot's instance number (cell +0x40); that is a *road tile* of the plot
(plots.Grid.create: roadPlot), so plots are ordered by their lowest road tile, not by their anchor tile.
Also writes the wonder counts (cells of plot type 4..9, deduplicated by anchor, savefile.py map_counts).
usage: python -I export_save_terra_order.py <game_dir> <out.inc>"""
import os, sys, struct
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import export_scene as E, plots

game, out = sys.argv[1], sys.argv[2]
names = ['%02d' % i for i in range(1, 12)] + ['download201', 'download202', 'download203', 'download204']
lines = ['// generated by scripts/export_save_terra_order.py: original terra order -> port plot index, and the wonder count of each map']
table = []
for mid in names:
    m = E.load_map(os.path.join(game, 'Map', mid + '.map'))
    W, H = m['W'], m['H']; hgt = m['heights']
    roadmesh = [False] * (W * H)
    for y in range(H):
        for x in range(W):
            rc = E.route_code(m['road'], x, y)
            if rc and 0 < rc[1] < 100: roadmesh[y * W + x] = True
    grid = plots.Grid(W, H, [int(v) for v in m['road'].flatten()], m['levels'], hgt, roadmesh)
    placed = grid.place_all([(int(m['plot'].flat[i]), int(m['anchor'].flat[i])) for i in range(W * H)])
    terras = [p for p in placed if p['result'] and p['result']['type'] in (1, 2)]
    order = sorted(range(len(terras)), key=lambda k: min(terras[k]['result']['roads']))
    # wonders: cells with plot type 4..9 deduplicated by the anchor (+0x48)
    d = open(os.path.join(game, 'Map', mid + '.map'), 'rb').read()
    w, h = struct.unpack_from('<2i', d, 12)
    off = 12 + 0x3c + (w + 1) * (h + 1) * 0x14
    won = set()
    for i in range(w * h):
        f2c, f3c, f44, f48, f60, f1c, f34 = struct.unpack_from('<7i', d, off + i * 0x1c)
        if f2c != 0 and 4 <= (f44 & 0xff) <= 9: won.add(f48)
    n = mid.replace('download', 'd')
    lines.append('static const int RM8TO_%s[] = {%s};' % (n, ','.join(str(v) for v in order)))
    table.append((mid, n, len(order), len(won)))
lines.append('static const struct { const char *dir; const int *order; int n, wonders; } RM8TO_TABLE[] = {')
for mid, n, cnt, wn in table:
    lines.append('\t{"%s", RM8TO_%s, %d, %d},' % (mid, n, cnt, wn))
lines.append('};')
open(out, 'w', encoding='ascii').write('\n'.join(lines) + '\n')
print('wrote', out)
