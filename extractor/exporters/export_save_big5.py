"""Writes port/app/save_big5.inc: the Big5 codes of every non-ASCII character of the stock names (scenes/stocks.txt), so that the
port's records carry the stock names in the original's encoding (stock object +0x000, 0x100 bytes of Big5; docs/save_port.md).
usage: python -I export_save_big5.py <stocks.txt> <out.inc>"""
import sys
chars = set()
for l in open(sys.argv[1], encoding='utf-8'):
    t = l.rstrip('\n').split('\t')
    if len(t) >= 7 and t[0] == 'stock':
        chars.update(t[6])
rows = []
for c in sorted(chars):
    if ord(c) < 128: continue
    b = c.encode('cp950')
    assert len(b) == 2
    rows.append((ord(c), b[0] << 8 | b[1]))
with open(sys.argv[2], 'w', encoding='ascii') as f:
    f.write('// generated by scripts/export_save_big5.py: {unicode, Big5 code}\n')
    for i in range(0, len(rows), 8):
        f.write(''.join('{0x%04x,0x%04x},' % r for r in rows[i:i + 8]) + '\n')
print(len(rows), 'characters')
