void rm8NetWaitToggle(int k)
{
	if(S.role != 1 || !S.waitPlayers || k < 0 || k >= (int)S.cur.size()) return;
	int o = S.cur.peer[k], &st = S.waitState[k];
	if(o > 0 && peerConnected(o) && st != RM8W_LOCAL) return;	// a player who is here keeps the seat
	switch(st){
	case RM8W_LOCAL: if(S.savedPeer[k] >= 0){ st = RM8W_SAVED; ownerSet(S.cur, k, S.savedPeer[k]); } else { st = RM8W_OPEN; ownerSet(S.cur, k, -1); } break;
	case RM8W_SAVED: case RM8W_OPEN: st = RM8W_LOCAL; ownerSet(S.cur, k, 0); break;
	case RM8W_COMPUTER: st = RM8W_COMPUTER_OPEN; ownerSet(S.cur, k, -1); break;
	case RM8W_COMPUTER_OPEN: st = RM8W_COMPUTER; ownerSet(S.cur, k, -1); break;
	}
	rm8Log("net: waiting: seat %d -> state %d (owner %d)", k, st, S.cur.peer[k]);
	sendRoom(true);
}
bool rm8NetWaitStart(bool force)
{
	if(S.role != 1 || !S.waitPlayers) return false;
	Rm8NetWaitView v = rm8NetWaitView();
	if(v.missing && !force) return false;
	S.waitPlayers = false;
	int bots = 0;
	for(size_t k = 0; k < S.cur.size(); k++){
		int st = S.waitState[k], o = S.cur.peer[k];
		bool present = seatPresent((int)k);
		if(st == RM8W_COMPUTER) continue;
		if(st == RM8W_COMPUTER_OPEN){	// an offered computer seat: a player seat played by the computer until its player is here
			pushHost(RM8C_ADOPT, (int)k, 0);
			if(present && o >= 0) pushHost(RM8C_AUTOSET, (int)k, 0);	// frame 1 is the record's quiet point: the player takes it at once
			else { S.autoByHost[k] = 1; S.openSeat[k] = o < 0; bots++; }
			continue;
		}
		if(!present){	// a player who is not back (or an open seat): the computer plays it meanwhile ([N] docs/netplay.md 9.1)
			if(rm8TurnHuman((int)k)) pushHost(RM8C_AUTOSET, (int)k, 1);
			S.autoByHost[k] = 1; S.openSeat[k] = o < 0; bots++;
		}else if(o > 0 && rm8TurnAuto((int)k)) pushHost(RM8C_AUTOSET, (int)k, 0);	// back on a seat the record has under auto play (the host's own seats keep theirs)
	}
	S.atStart = S.atSnap = S.cur;
	sendRoom(false);
	sendStatus();
	S.acc = 0; S.lastFrameT = nowSec();
	rm8Log("net: the resumed game continues%s (%d seats played by the computer until their players come)", v.missing ? " without everybody" : "", bots);
	notice(v.missing ? "游戏继续：没回来的座位先由电脑托管，玩家加入后交还" : "所有玩家都回来了，游戏继续", 5);
	return true;
}

void rm8NetJoin(const std::string &addr)
{
	std::string host; int port = RM8_NET_DEFAULT_PORT;
	if(!rm8net::splitAddr(addr, host, port, RM8_NET_DEFAULT_PORT)){ S.joinState = "地址格式不对，应为 IP:端口，例如 192.168.1.5:47000"; return; }
	if(S.role == 1) rm8NetLeave("join");
	if(S.role == 2){ for(Conn &c : S.conns) connClose(c); S.conns.clear(); }
	S = Session(); S.role = 2; S.addr = addr; S.port = rm8NetPort();
	if(!rm8net::connectStart(host, port)){ S.joinState = "网络初始化失败"; S.role = 0; return; }
	S.connecting = true; S.joinState = "正在连接 " + host + ":" + std::to_string(port) + " …";
	dataHash();
	rm8Log("net: joining %s:%d as %s", host.c_str(), port, rm8NetMyName().c_str());
}

void rm8NetLeave(const char *why)
{
	if(S.role == 0){ S.resumeArmed = false; return; }
	rm8Log("net: leaving the session (%s)", why ? why : "");
	Rm8SaveW w; w.str(why ? why : "");
	if(S.role == 1){ for(Conn &c : S.conns) if(c.fd >= 0){ connSend(c, M_BYE, w); connPump(c); connClose(c); } if(S.lfd >= 0) rm8net::closeSock(S.lfd); }
	else { for(Conn &c : S.conns) if(c.fd >= 0){ connSend(c, M_BYE, w); connPump(c); connClose(c); } rm8net::connectCancel(); }
	int port = S.port;
	S = Session(); S.port = port;
	undoSessionOptions();
}
void rm8NetGameEnded(){ if(S.role != 0) rm8NetLeave("游戏结束"); }

void rm8NetAppPaused(bool paused)
{
	static double pausedAt = 0;
	if(paused){ pausedAt = nowSec(); if(S.role) rm8Log("net: the app went to the background"); return; }
	double t = nowSec();
	for(Conn &c : S.conns) if(c.fd >= 0){ c.lastRecv = std::max(c.lastRecv, t); c.lastPing = 0; }	// a grace period: the other side may have been quiet for us meanwhile
	S.acc = 0; S.lastConfirmT = t;
	if(S.role) rm8Log("net: back from the background after %.1f s", t - pausedAt);
}

