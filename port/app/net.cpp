double nowSec(){ static const auto t0 = std::chrono::steady_clock::now(); return std::chrono::duration<double>(std::chrono::steady_clock::now() - t0).count(); }
uint64_t fnv(const void *p, size_t n, uint64_t h = 1469598103934665603ull)
{
	const unsigned char *c = (const unsigned char*)p;
	for(size_t i = 0; i < n; i++){ h ^= c[i]; h *= 1099511628211ull; }
	return h;
}
uint32_t rnd32(){ static std::mt19937 g((unsigned)time(nullptr) ^ (unsigned)(nowSec() * 1e6)); return g(); }

