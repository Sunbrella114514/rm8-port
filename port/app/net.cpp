void connSend(Conn &c, int type, const Rm8SaveW &body)
{
	if(c.fd < 0) return;
	uint32_t len = (uint32_t)body.b.size() + 1;
	uint8_t h[5]; memcpy(h, &len, 4); h[4] = (uint8_t)type;
	c.out.insert(c.out.end(), h, h + 5);
	c.out.insert(c.out.end(), body.b.begin(), body.b.end());
}
// returns false when the connection died
bool connPump(Conn &c)
{
	if(c.fd < 0) return false;
	while(c.outPos < c.out.size()){
		int n = rm8net::sendSome(c.fd, c.out.data() + c.outPos, (int)std::min<size_t>(c.out.size() - c.outPos, 1 << 16));
		if(n < 0) return false;
		if(n == 0) break;
		c.outPos += (size_t)n;
	}
	if(c.outPos == c.out.size()){ c.out.clear(); c.outPos = 0; }
	else if(c.outPos > (1u << 20)){ c.out.erase(c.out.begin(), c.out.begin() + (ptrdiff_t)c.outPos); c.outPos = 0; }
	uint8_t buf[16384];
	for(int k = 0; k < 64; k++){
		int n = rm8net::recvSome(c.fd, buf, sizeof buf);
		if(n < 0) return false;
		if(n == 0) break;
		c.in.insert(c.in.end(), buf, buf + n);
		c.lastRecv = nowSec();
		if(c.in.size() > MAX_MSG + 64) return false;
	}
	return true;
}
// one complete message (type, payload) or false
bool connTake(Conn &c, int &type, std::vector<uint8_t> &payload, bool &bad)
{
	bad = false;
	if(c.in.size() < 5) return false;
	uint32_t len; memcpy(&len, c.in.data(), 4);
	if(len < 1 || len > MAX_MSG){ bad = true; return false; }
	if(c.in.size() < 4 + (size_t)len) return false;
	type = c.in[4];
	payload.assign(c.in.begin() + 5, c.in.begin() + 4 + len);
	c.in.erase(c.in.begin(), c.in.begin() + 4 + len);
	return true;
}
void connClose(Conn &c){ if(c.fd >= 0) rm8net::closeSock(c.fd); c.fd = -1; c.in.clear(); c.out.clear(); c.outPos = 0; }

// remote text: at most `max` bytes (cut on a UTF-8 character boundary), no control characters
std::string cleanStr(const std::string &s, size_t max)
{
	size_t n = std::min(s.size(), max);
	while(n > 0 && n < s.size() && ((unsigned char)s[n] & 0xC0) == 0x80) n--;
	std::string o = s.substr(0, n);
	for(char &ch : o) if((unsigned char)ch < 0x20) ch = ' ';
	return o;
}
bool cleanName(const std::string &s){ if(s.empty() || s.size() > 40) return false; for(char c : s) if(!(isalnum((unsigned char)c) || c == '_' || c == '-')) return false; return true; }

