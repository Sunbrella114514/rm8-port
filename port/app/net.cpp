// ---- data hash: everything the simulation reads besides the 3D / texture packs (docs/netplay.md 4.2)
uint64_t dataHash()
{
	if(g_dataHashed) return g_dataHash;
	g_dataHashed = true;
	uint64_t h = fnv("rm8data", 7);
	std::vector<std::pair<std::string, fs::path>> keyed;	// "scenes/..." / "game/..." (lower case, '/') -> file
	std::error_code ec;
	auto addDir = [&](const fs::path &d, const std::string &prefix, bool txtOnly){
		for(auto &e : fs::directory_iterator(d, ec)){
			if(!e.is_regular_file(ec)) continue;
			std::string ext = e.path().extension().string(); for(char &c : ext) c = (char)tolower((unsigned char)c);
			if(txtOnly && ext != ".txt") continue;
			std::string k = prefix + e.path().filename().string();
			for(char &c : k) c = (char)tolower((unsigned char)c);
			keyed.push_back({k, e.path()});
		}
	};
	addDir(g_scenes, "scenes/", true);
	for(auto &e : fs::directory_iterator(g_scenes, ec)) if(e.is_directory(ec)) addDir(e.path(), "scenes/" + e.path().filename().string() + "/", true);
	addDir(fs::path(g_gameDir) / "Pysrc", "game/pysrc/", false);
	// [N] game/Config is NOT hashed: the app reads only Config/init.txt there (per-device settings; the host's options travel in START) and, optionally,
	// gamedate.bin (per-player progress); the Steam install also keeps steam_autocloud.vdf etc. there, and a phone with adb-pushed data has init.txt only
	std::sort(keyed.begin(), keyed.end());
	std::vector<char> buf;
	for(auto &kp : keyed){
		std::ifstream f(kp.second, std::ios::binary);
		buf.assign(std::istreambuf_iterator<char>(f), std::istreambuf_iterator<char>());
		h = fnv(kp.first.data(), kp.first.size(), h); h = fnv(buf.data(), buf.size(), h);
	}
	// the sound pack's index: the deterministic voice waits take their lengths from it (audio.cpp), the sizes stand in for the whole pack
	{
		std::ifstream f(fs::path(g_gameDir) / "Sound" / "snd0000.dat", std::ios::binary);
		char hd[12]; uint32_t n = 0;
		if(f.read(hd, 12)){ memcpy(&n, hd + 8, 4); if(n < 100000){ std::vector<char> idx((size_t)n * 16); f.read(idx.data(), (std::streamsize)idx.size()); h = fnv(hd, 12, h); h = fnv(idx.data(), (size_t)f.gcount(), h); } }
	}
	g_dataHash = h;
	rm8Log("net: data hash %016llx over %d files", (unsigned long long)h, (int)keyed.size());
	return h;
}

