		for(int k = 0; k < n; k++){ int id = r.i32(); bool c = r.u8() != 0; std::string nm = cleanStr(r.str(), MAX_NAME); if(id >= 0 && id < n){ S.peers[id].id = id; S.peers[id].connected = c; S.peers[id].name = nm; } }
