	putU64(w, S.id); w.u32(S.seed);
	for(int d : S.date) w.i32(d);
	w.i32(S.speed); w.i32(S.difficulty); w.i32(S.plus);
	const Rm8Setup &st = S.setup;
	w.i32(st.map); w.i32(st.cash); w.i32(st.tickets); w.i32(st.vehicle); w.i32(st.timeLimit); w.i32(st.winCond);
