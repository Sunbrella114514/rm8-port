// ======================================================================== public: main loop
void rm8NetPoll()
{
	if(S.role == 0) return;
	double t = nowSec();
	if(S.role == 1){
		// new connections
		for(int k = 0; k < 8; k++){
			std::string peer;
			intptr_t fd = rm8net::acceptTcp(S.lfd, peer);
			if(fd < 0) break;
			Conn c; c.fd = fd; c.addr = peer; c.lastRecv = c.opened = t;
			bool reused = false;
			for(Conn &o : S.conns) if(o.fd < 0 && o.peer < 0){ o = c; reused = true; break; }
			if(!reused) S.conns.push_back(c);
			rm8Log("net: connection from %s", peer.c_str());
		}
		for(size_t i = 0; i < S.conns.size(); i++){
			Conn &c = S.conns[i];
			if(c.fd < 0) continue;
			bool alive = connPump(c);
			int type; std::vector<uint8_t> pl; bool bad = false;
			while(alive && !S.conns[i].closing && connTake(S.conns[i], type, pl, bad)){ Rm8SaveR r(pl.data(), pl.size()); hostMessage(S.conns[i], type, r); if(S.role != 1) return; }
			Conn &cc = S.conns[i];
			if(bad) alive = false;
			if(cc.peer < 0 && !cc.closing && t - cc.opened > HELLO_TIMEOUT){ reject(cc, "握手超时（对方没有按联机协议发送数据）"); }
			if(alive && t - cc.lastRecv > PEER_TIMEOUT) alive = false;
			if(alive && t - cc.lastPing > PING_EVERY){ cc.lastPing = t; Rm8SaveW w; w.u32((uint32_t)(t * 1000.0)); connSend(cc, M_PING, w); }
			if(cc.closing){ connPump(cc); if(cc.out.empty() || t - cc.lastRecv > 2){ int p = cc.peer; connClose(cc); cc.peer = -1; if(p > 0 && p < (int)S.peers.size() && S.peers[p].conn == (int)i) peerLost(p, "closed"); } continue; }
			if(!alive){ int p = cc.peer; connClose(cc); cc.peer = -1; if(p > 0 && p < (int)S.peers.size() && S.peers[p].conn == (int)i) peerLost(p, "connection lost"); }
		}
		if(S.lobby) hostLobbyTick(t);
		if(S.inGame && S.waitLoaded){
			bool all = true; for(const Peer &p : S.peers) if(p.connected && !p.loaded) all = false;
			if(all || t - S.waitLoadedSince > 20){ S.waitLoaded = false; rm8Log("net: %s, the game runs", all ? "every player has built the board" : "waited 20 s for the boards"); }
		}
		// test hook RM8_NET_RESUME_AUTOSTART=all | <s> | all,<s>: the waiting screen continues once every player is back / after s seconds without them
		if(S.inGame && S.waitPlayers) if(const char *e = getenv("RM8_NET_RESUME_AUTOSTART")){
			bool all = strncmp(e, "all", 3) == 0; const char *c = strchr(e, ','); double secs = all ? (c ? atof(c + 1) : -1) : atof(e);
			Rm8NetWaitView v = rm8NetWaitView();
			if(t - S.waitSince > 4 && ((all && v.missing == 0) || (secs >= 0 && t - S.waitSince > secs))) rm8NetWaitStart(true);
		}
		hostFlush(false);
		for(Conn &c : S.conns) if(c.fd >= 0) connPump(c);
	}else{
		if(S.connecting){
			intptr_t fd; std::string err;
			int st = rm8net::connectPoll(fd, err);
			if(st == 1){ Conn c; c.fd = fd; c.lastRecv = c.opened = t; S.conns.clear(); S.conns.push_back(c); S.connecting = false; S.joinState = "已连接，正在握手…"; clientSendHello(); }
			else if(st < 0){ S.connecting = false; if(!S.reconnecting){ S.joinState = err; S.role = 0; notice(err, 8); } else S.nextTry = t + 2; }
		}
		if(!S.conns.empty() && S.conns[0].fd >= 0){
			Conn &c = S.conns[0];
			bool alive = connPump(c);
			int type; std::vector<uint8_t> pl; bool bad = false;
			while(alive && !S.conns.empty() && connTake(S.conns[0], type, pl, bad)){ Rm8SaveR r(pl.data(), pl.size()); clientMessage(type, r); if(S.role != 2) return; }
			if(S.conns.empty()) return;
			Conn &cc = S.conns[0];
			if(bad) alive = false;
			if(alive && t - cc.lastRecv > PEER_TIMEOUT) alive = false;
			if(alive && t - cc.lastPing > PING_EVERY){ cc.lastPing = t; Rm8SaveW w; w.u32((uint32_t)(t * 1000.0)); connSend(cc, M_PING, w); }
			// test hook RM8_NET_DROP_AT=<s>[,<down s>]: the client drops its connection once (the reconnect test)
			if(g_test.dropAt >= 0 && !g_test.dropped && S.inGame && S.frame * RM8_NET_STEP >= g_test.dropAt){ g_test.dropped = true; alive = false; g_test.dropT = t; rm8Log("net: test: dropping the connection at frame %u", S.frame); }
			// [N4] test hook RM8_NET_MINI_DROP=<s>[,<down s>[,keep][,g<game>]]: the client drops its connection <s> seconds into its own minigame (once); keep = the old socket
			// stays open, so the host does not see the loss and only notices the reconnect (its HELLO with the ticket)
			bool leak = false;
			if(g_test.miniDropAt >= 0 && !g_test.miniDropped && S.inGame){
				Rm8MiniWaitInfo mi;
				if(rm8EventMiniWaiting(&mi) && mi.local && mi.playing && (!g_test.miniDropGame || g_test.miniDropGame == mi.game)){
					if(mi.serial != g_test.miniSerial){ g_test.miniSerial = mi.serial; g_test.miniPlayT = t; }
					if(t - g_test.miniPlayT >= g_test.miniDropAt){ g_test.miniDropped = true; alive = false; leak = g_test.miniDropKeep; g_test.dropped = true; g_test.dropT = t; g_test.dropFor = g_test.miniDropFor; rm8Log("net: test: dropping the connection %.1f s into minigame %d (frame %u)%s", t - g_test.miniPlayT, mi.game, S.frame, leak ? ", the old socket stays open" : ""); }
				}
			}
			if(alive) connPump(cc);
			else{
				if(leak) cc.fd = -1;	// (test) leaked on purpose
				connClose(cc); S.conns.clear();
				if(S.inGame || S.token){ S.reconnecting = true; S.reconnectUntil = t + RECONNECT_FOR; S.nextTry = t + (g_test.dropped && t - g_test.dropT < 1 ? g_test.dropFor : 1.0); notice("与主机的连接中断，正在重连…", 6); }
				else { S.joinState = "与主机的连接中断"; S.role = 0; }
			}
		}
		if(S.reconnecting && !S.connecting && S.conns.empty()){
			if(t > S.reconnectUntil){ clientEnd(S.inGame ? "无法重新连接主机（90 秒内没有连上），游戏已退出" : "无法重新连接主机"); return; }
			if(t >= S.nextTry){
				std::string host; int port;
				if(rm8net::splitAddr(S.addr, host, port, RM8_NET_DEFAULT_PORT) && rm8net::connectStart(host, port)){ S.connecting = true; S.joinState = "正在重连…"; rm8Log("net: reconnecting to %s", S.addr.c_str()); }
				S.nextTry = t + 3;
			}
		}
		// test hook RM8_NET_PICK=<character>: the client asks for that character of its seat once it is in the room
		if(!g_test.pickSent && S.room.valid && S.room.mySeat >= 0 && S.room.screen == 2) if(const char *e = getenv("RM8_NET_PICK")){ g_test.pickSent = true; rm8NetRoomPickRole(atoi(e), -1); rm8Log("net: test: asking for character %d", atoi(e)); }
	}
	pollHover();
	monkeyStep();
	{	// RM8_NET_TRACE: a status line every 5 s (who the game waits for, which dialogs are open)
		static const bool tr = getenv("RM8_NET_TRACE") != nullptr; static double lastT = 0;
		if(tr && S.inGame && t - lastT > 5){
			lastT = t;
			int is = rm8NetInputSeat();
			std::vector<Rm8UiButtonInfo> bs; rm8UiListButtons(bs);
			std::string uis; for(const Rm8UiButtonInfo &b : bs) if(uis.find(b.ui) == std::string::npos) uis += " " + b.ui;
			rm8Log("net: status frame %u (confirmed %u) input seat %d state %d human %d, current %d, event %d, picking %d, may decide %d, waiting %d, clickable:%s", S.frame, S.confirmed, is, is >= 0 ? rm8TurnState(is) : -1, is >= 0 ? (int)rm8TurnHuman(is) : -1, rm8TurnCurrent(), (int)rm8EventRunning(), (int)rm8CardsPicking(), (int)mayDecide(S.localPeer), (int)S.waitPlayers, uis.c_str());
		}
	}
	if(S.role == 1 && S.inGame && !g_test.fastSent && getenv("RM8_NET_FAST") && S.frame > 30){ g_test.fastSent = true; rm8NetInput(RM8C_FAST); }
}

int rm8NetStepsDue(float realDt)
{
	if(!S.inGame) return 0;
	realDt *= g_test.timeScale;
	S.acc += std::max(0.0f, std::min(0.25f * g_test.timeScale, realDt));
	int due = (int)(S.acc / RM8_NET_STEP);
	if(S.waitPlayers){ S.acc = 0; return 0; }	// a resumed game waits at frame 0
	if(S.role == 1){
		if(S.waitLoaded){ S.acc = 0; return 0; }
		int n = std::min(due, (int)(8 * g_test.timeScale) + 1);
		S.acc -= n * RM8_NET_STEP;
		if(S.acc > 4 * RM8_NET_STEP) S.acc = 4 * RM8_NET_STEP;	// a slow device slows the game down instead of bursting
		return n;
	}
	if(S.resyncing && S.reconnecting) return 0;
	int avail = (int)(S.confirmed - S.frame);
	if(avail <= 0){ if(S.acc > 2 * RM8_NET_STEP) S.acc = 2 * RM8_NET_STEP; return 0; }
	int n = std::min(due, avail);
	int behind = avail - n;
	if(behind > 6) n = std::min(avail, n + std::max(1, behind / 4));	// catch up (after a stall, a load or a resync)
	n = std::min(n, behind > 600 ? 90 : 16);
	S.acc -= std::min(n, due) * RM8_NET_STEP;
	if(S.acc < 0) S.acc = 0;
	return n;
}

void rm8NetFrameBegin()
{
	if(!S.inGame) return;
	uint32_t f = S.frame + 1;
	S.simFrame = f;
	if(S.role == 1) hostScheduleFrame(f);
	else{
		while(!S.queue.empty() && S.queue.front().frame < f) S.queue.pop_front();	// (cannot happen: the host's frames only grow)
		while(!S.queue.empty() && S.queue.front().frame == f){ Rm8NetCommand c = S.queue.front(); S.queue.pop_front(); apply(c); }
		// test hook RM8_NET_DESYNC_AT=<frame>: this client's state is broken once (the resync test)
		if(g_test.desyncAt >= 0 && !g_test.desynced && (int)f >= g_test.desyncAt){ g_test.desynced = true; rm8GameAddMoney(0, 777, false); rm8Log("net: test: local desync injected at frame %u (seat 0 cash + 777)", f); }
	}
}
void rm8NetFrameEnd(){ if(S.inGame) S.frame = S.simFrame; }

// ======================================================================== the simulation camera
void rm8NetPlaceSimCamera(Camera *cam, const Rm8Scene &sc, float fx, float fz)
{
	// sin / cos of yaw 225 and pitch 40 as exact decimal constants (the compiler rounds them the same way everywhere; no libm call)
	const float SY = -0.70710678118654752f, CY = -0.70710678118654752f, SP = 0.64278760968653933f, CP = 0.76604444311897804f;
	float ext = sc.MW * 25.0f * 1.42f, dist = ext * 2.0f * 0.176f;
	cam->setNearPlane(10.0f); cam->setFarPlane(ext * 6.0f);
	V3d eye = {fx + dist * CP * SY, dist * SP, fz - dist * CP * CY};
	V3d fwd = {fx - eye.x, -eye.y, fz - eye.z};
	float l = sqrtf(fwd.x * fwd.x + fwd.y * fwd.y + fwd.z * fwd.z);
	fwd.x /= l; fwd.y /= l; fwd.z /= l;
	V3d up = {0, 1, 0};
	Matrix m; m.setIdentity(); m.lookAt(fwd, up); m.pos = eye;
	cam->getFrame()->transform(&m, COMBINEREPLACE);
}

