void hostMessage(Conn &c, int type, Rm8SaveR &r)
{
	if(c.peer < 0 && type != M_HELLO && type != M_PING && type != M_PONG){ reject(c, "握手失败"); return; }
	Peer *p = c.peer >= 0 && c.peer < (int)S.peers.size() ? &S.peers[c.peer] : nullptr;
	switch(type){
	case M_HELLO: if(c.peer < 0) hostHello(c, r); break;
	case M_PING: { Rm8SaveW w; w.u32(r.u32()); connSend(c, M_PONG, w); break; }
	case M_PONG: { uint32_t t = r.u32(); c.rtt = (float)(nowSec() * 1000.0 - t) / 1000.0f; break; }
	case M_READY: if(p && S.lobby){ p->ready = r.u8() != 0; S.lastLobby.clear(); rm8Log("net: room: peer %d %s", p->id, p->ready ? "is ready" : "is not ready"); } break;
	case M_PICK: if(p && S.lobby){
		int ch = r.i32(), of = r.i32();
		if(r.bad || ch > 16 || of > 4) break;
		bool done = false;
		for(auto &sp : S.seatPeer) if(sp.second == p->id){ done = rm8MenuNetSetSeatRole(sp.first, ch, of); break; }
		rm8Log("net: room: peer %d asks for character %d outfit %d: %s", p->id, ch, of, done ? "done" : "refused");
		S.lastLobby.clear();
		} break;
	case M_LOADED: if(p){ uint32_t f = r.u32(); p->loaded = true; p->resyncing = false; rm8Log("net: peer %d loaded its board at frame %u", p->id, f);
		for(size_t k = 0; k < S.cur.size(); k++) if(S.cur.peer[k] == p->id && k < S.autoByHost.size() && S.autoByHost[k]) S.autoByHost[k] = 2;	// give the seat back once the player runs again
		if(S.waitPlayers) sendRoom(true);
		} break;
	case M_CMD: if(p && S.inGame){
		Rm8NetCommand k; if(!getCmd(r, k)) break;
		if(k.kind == RM8C_AUTOSET || k.kind == RM8C_FAST || k.kind == RM8C_SEAT || k.kind == RM8C_ADOPT) break;	// host-only kinds ([N4] RM8C_MINI_RESULT comes from the minigame's player: permitted() checks it)
		if((k.kind == RM8C_UI_CLICK || k.kind == RM8C_UI_HOVER) && !(k.s.empty() || cleanName(k.s))) break;
		k.seat = p->id; S.pending.push_back(k);
		} break;
	case M_HASH: if(p && S.inGame){ uint32_t f = r.u32(); int kind = r.i32(); uint64_t h = getU64(r); if(!r.bad) hostCompareHash(*p, f, kind, h); } break;
	case M_BYE: if(p){ c.closing = true; peerLost(p->id, "left"); } break;
	case M_CHAT: if(p){ std::string t = r.str(); if(!r.bad) hostChat(p->id, t); } break;
	default: break;
	}
}

// a seat can change hands when the game does not wait for it and it is not its turn (a turn boundary for that seat)
bool safeSeat(int k){ return rm8TurnCurrent() != k && rm8NetInputSeat() != k; }
// the host schedules the pending commands at the frame that starts now
void hostScheduleFrame(uint32_t f)
{
	// give an absent player's seat back once it is home again / hand an open seat to its new player (retried: autoDisable fails while the role is in an event)
	if(nowSec() - S.lastAutoTry > 0.5){
		S.lastAutoTry = nowSec();
		for(size_t k = 0; k < S.cur.size(); k++){
			int pc = S.pendingClaim[k];
			if(pc > 0){
				Peer &p = S.peers[pc];
				if(!p.connected){ S.pendingClaim[k] = -1; continue; }
				if(!p.loaded || !safeSeat((int)k)) continue;
				char b[24]; snprintf(b, sizeof b, "%016llx ", (unsigned long long)p.playerId);
				pushHost(RM8C_SEAT, (int)k, pc, b + cleanStr(p.name, MAX_NAME));
				if(rm8TurnAuto((int)k)) pushHost(RM8C_AUTOSET, (int)k, 0);
				S.pendingClaim[k] = -1; S.autoByHost[k] = 0; S.openSeat[k] = 0;
				notice(peerName(pc) + " 接手了 " + roleName((int)k));
				continue;
			}
			if(S.autoByHost[k] != 2) continue;
			int o = ownerOf((int)k);
			if(!peerConnected(o)){ S.autoByHost[k] = 1; continue; }
			if(!rm8TurnAuto((int)k)){ S.autoByHost[k] = 0; continue; }
			if(!safeSeat((int)k)) continue;	// [N2] at a turn boundary: not while the seat acts
			pushHost(RM8C_AUTOSET, (int)k, 0);
		}
	}
	{	// [N4] a minigame waits for its result: the host decides with the computer logic when its player is away (disconnected / no player) or took too long;
		// a seat of the host itself is played here and has no timeout
		Rm8MiniWaitInfo mi;
		if(!S.waitPlayers && rm8EventMiniWaiting(&mi) && mi.group) hostMini21(mi);
		else if(!S.waitPlayers && rm8EventMiniWaiting(&mi) && S.miniDecided != mi.serial){
			int o = ownerOf(mi.seat);
			if(mi.serial != S.miniSeen){ S.miniSeen = mi.serial; S.miniSeenT = nowSec(); }
			if(o < 0 || !peerConnected(o)) miniDecide(mi, "玩家不在线");
			else if(o != 0 && nowSec() - S.miniSeenT > miniTimeoutSec()) miniDecide(mi, "等待超时");
		}
	}
	while(!S.pending.empty()){
		Rm8NetCommand c = S.pending.front(); S.pending.pop_front();
		if(!permitted(c, c.seat)) continue;
		c.frame = f;
		S.log.push_back(c); S.outBatch.push_back(c);
		apply(c);
	}
	for(Peer &p : S.peers) if(p.baseDue){ p.baseDue = false; if(p.connected) sendBase(p); }	// [N4] after the frame that applies the host's minigame decision
}

void hostFlush(bool force)
{
	if(S.role != 1 || !S.inGame) return;
	static double last = 0;
	if(!force && S.outBatch.empty() && nowSec() - last < 0.033) return;
	if(S.frame == S.sentUpTo && S.outBatch.empty()) return;
	last = nowSec();
	Rm8SaveW w; w.u32(S.frame); w.i32((int)S.outBatch.size());
	for(const Rm8NetCommand &c : S.outBatch) putCmd(w, c);
	for(Conn &c : S.conns) if(c.fd >= 0 && c.peer > 0 && !c.closing && !(c.peer < (int)S.peers.size() && S.peers[c.peer].baseDue)) connSend(c, M_FRAMES, w);	// a resyncing peer gets the batches too (its base + log came first, in order); [N4] not before a base that is due (the base log covers this batch)
	S.outBatch.clear(); S.sentUpTo = S.frame;
}

