std::string peerName(int peer)
{
	if(peer < 0) return "电脑";
	if(peer < (int)S.peers.size() && !S.peers[peer].name.empty()) return S.peers[peer].name;
	if(peer == 0) return "主机";
	char b[32]; snprintf(b, sizeof b, "玩家%d", peer + 1); return b;
}
bool peerConnected(int p){ if(p == S.localPeer && p >= 0) return true; return p >= 0 && p < (int)S.peers.size() && S.peers[p].connected; }
int ownerOf(int seat){ return seat >= 0 && seat < (int)S.cur.size() ? S.cur.peer[seat] : -1; }
int seatOf(int peer){ for(size_t k = 0; k < S.cur.size(); k++) if(S.cur.peer[k] == peer) return (int)k; return -1; }
void ownerSet(Owners &o, int seat, int peer)
{
	if(seat < 0 || seat >= (int)o.size()) return;
	o.peer[seat] = peer;
	if(peer < 0){ o.name[seat].clear(); o.id[seat] = 0; return; }
	o.name[seat] = cleanStr(peerName(peer), MAX_NAME);
	o.id[seat] = peer < (int)S.peers.size() ? S.peers[peer].playerId : 0;
}
std::string roleName(int seat){ return seat >= 0 && seat < rm8TurnRoleCount() ? rm8TurnName(seat) : std::string("?"); }

