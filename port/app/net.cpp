// may `peer` decide what the game waits for now? (the host may also answer for a player who is away: the game must not hang on a dialog)
bool mayDecide(int peer)
{
	if(S.waitPlayers) return false;
	if(rm8EventMiniWaiting()) return false;	// [N4] a minigame runs on its player's device: nobody decides anything on the board until its result is applied
	int s = rm8NetInputSeat();
	if(s < 0 || !rm8TurnHuman(s)) return false;
	int o = ownerOf(s);
	if(o == peer) return true;
	return peer == 0 && S.role == 1 && o >= 0 && !peerConnected(o);
}
bool permitted(const Rm8NetCommand &c, int peer)
{
	switch(c.kind){
	case RM8C_AUTOKEY: return ownerOf(c.a) == peer;
	case RM8C_AUTOSET: case RM8C_FAST: case RM8C_SEAT: case RM8C_ADOPT: return peer == 0;
	case RM8C_MINI_RESULT: {	// [N4] the waiting minigame's own player (its result, or "computer" when it cannot run the game), the host (the computer logic: player away / late)
		Rm8MiniWaitInfo mi;
		if(S.waitPlayers || !rm8EventMiniWaiting(&mi) || mi.group || c.a != mi.game) return false;
		if(peer == 0 && c.b == 1) return true;
		return ownerOf(mi.seat) == peer;
	}
	case RM8C_MINI_ACT: {	// [N4] 插海盗 with everybody: the player whose turn it is (his seat's choices), the host (the computer's choice: any turn), DONE from anybody, FINAL from the host
		Rm8MiniWaitInfo mi;
		if(S.waitPlayers || !rm8EventMiniWaiting(&mi) || !mi.group || c.a != mi.game) return false;
		unsigned ser = 0; int turn = 0, arg = 0;
		if(sscanf(c.s.c_str(), "%u,%d,%d", &ser, &turn, &arg) != 3 || ser != mi.serial) return false;
		bool mine = mi.turnHuman && ownerOf(mi.turnSeat) == peer;
		switch(c.b){
		case RM8M21_ROT: case RM8M21_STAB: return !mi.finished && turn == mi.turn && mine;
		case RM8M21_AUTO: return !mi.finished && turn == mi.turn && (mine || peer == 0);
		case RM8M21_DONE: return mi.finished && peer >= 0;
		case RM8M21_FINAL: return mi.finished && peer == 0;
		default: return false;
		}
	}
	default: return mayDecide(peer);
	}
}
void apply(const Rm8NetCommand &c)
{
	if(c.kind > 0 && c.kind < RM8C_COUNT) g_applied[c.kind]++;
	static const bool trace = getenv("RM8_NET_TRACE") != nullptr;
	if(trace) rm8Log("net: f%u apply kind %d seat %d a %d b %d %s", c.frame, c.kind, c.seat, c.a, c.b, c.s.c_str());
	switch(c.kind){
	case RM8C_UI_CLICK: rm8UiNetApplyClick(c.s, c.a); break;
	case RM8C_UI_HOVER: rm8UiNetApplyHover(c.s, c.a); break;
	case RM8C_ROLL: rm8RolesHumanRoll(); break;
	case RM8C_CARD: rm8CardsNetApply(c.a, c.b); break;
	case RM8C_SKIP: rm8SkipRequestNow(); break;
	case RM8C_FAST: rm8SkipToggleFastNow(); break;
	case RM8C_AUTOKEY: if(!rm8EventRunning()) rm8AutoKey(c.a); break;	// [V] the F keys do nothing while an event dialog runs (autoPlayKey)
	case RM8C_AUTOSET: rm8AutoSet(c.a, c.b != 0); break;
	case RM8C_AUTOASK: rm8AutoSupplyOpen(); break;
	case RM8C_SEAT:	// [N2] a seat's player changes (NETP follows on every peer at this frame)
		if(c.a >= 0 && c.a < (int)S.cur.size()){
			size_t sp = c.s.find(' ');
			S.cur.peer[c.a] = c.b; S.cur.id[c.a] = strtoull(c.s.substr(0, sp).c_str(), nullptr, 16); S.cur.name[c.a] = sp == std::string::npos ? std::string() : c.s.substr(sp + 1);
			rm8Log("net: seat %d is played by peer %d (%s) from frame %u", c.a, c.b, S.cur.name[c.a].c_str(), c.frame);
		}
		break;
	case RM8C_ADOPT: rm8AutoAdopt(c.a); break;
	case RM8C_MINI_RESULT:	// [N4] stored in the waiting minigame task; its update in this frame hands out the rewards (event_mini.cpp)
		if(!rm8EventMiniResult(c.a, c.b, c.s)) rm8Log("net: f%u minigame %d result ignored (no minigame waits for it)", c.frame, c.a);
		else rm8Log("net: f%u minigame %d result from peer %d: %s", c.frame, c.a, c.seat, c.b == 1 ? "the computer logic decides" : c.s.c_str());
		break;
	case RM8C_MINI_ACT:	// [N4] the referee of the waiting game 21 (event_mini.cpp); a stale one (its turn was decided already) is ignored the same way everywhere
		if(!rm8EventMiniAct(c.a, c.b, c.seat, c.s) && trace) rm8Log("net: f%u minigame action %d %s from peer %d ignored (stale)", c.frame, c.b, c.s.c_str(), c.seat);
		break;
	default: break;
	}
}

// ======================================================================== host side
Conn *peerConn(int p){ if(p < 0 || p >= (int)S.peers.size()) return nullptr; int ci = S.peers[p].conn; return ci >= 0 && ci < (int)S.conns.size() && S.conns[ci].fd >= 0 ? &S.conns[ci] : nullptr; }
void reject(Conn &c, const std::string &why){ Rm8SaveW w; w.str(why); connSend(c, M_REJECT, w); c.closing = true; rm8Log("net: reject %s: %s", c.addr.c_str(), why.c_str()); }
void pushHost(int kind, int a, int b, const std::string &s = std::string()){ Rm8NetCommand c; c.kind = kind; c.seat = 0; c.a = a; c.b = b; c.s = s; S.pending.push_back(c); }

const Owners &baseOwners(){ return S.waitPlayers ? S.cur : S.haveSnap ? S.atSnap : S.atStart; }
void sendBase(Peer &p)
{
	Conn *c = peerConn(p.id);
	if(!c) return;
	{ Rm8SaveW w; writeStart(w, 1, baseOwners()); connSend(*c, M_START, w); }
	Rm8SaveW w;
	if(S.haveSnap){ w.u32(S.snapFrame); w.u8(1); w.u32((uint32_t)S.snap.size()); w.raw(S.snap.data(), S.snap.size()); p.baseFrame = S.snapFrame; }
	else { w.u32(0); w.u8(0); w.u32(0); p.baseFrame = 0; }
	connSend(*c, M_BASE, w);
	// [N4] fix: only the commands of the frames already sent (<= sentUpTo); the ones of the frames since (still in outBatch) follow with the next FRAMES batch,
	// which a resyncing peer gets too - before, a base between a frame's scheduling and the flush delivered those commands twice
	Rm8SaveW f; f.u32(std::max(S.sentUpTo, p.baseFrame)); int nl = 0;
	for(const Rm8NetCommand &k : S.log) if(k.frame <= S.sentUpTo) nl++;
	f.i32(nl);
	for(const Rm8NetCommand &k : S.log) if(k.frame <= S.sentUpTo) putCmd(f, k);
	connSend(*c, M_FRAMES, f);
	p.resyncing = true; p.loaded = false;
	S.resyncs++;
	rm8Log("net: base to peer %d: %s frame %u, %d commands to replay, host at %u (sent up to %u)", p.id, S.haveSnap ? "snapshot" : "start", p.baseFrame, nl, S.frame, S.sentUpTo);
}
int miniTimeoutSec(){ static const int t = getenv("RM8_NET_MINI_TIMEOUT") ? std::max(5, atoi(getenv("RM8_NET_MINI_TIMEOUT"))) : 300; return t; }	// [N4] the host's safety net (5 minutes)
// [N4] the host decides the waiting minigame with the computer logic (RM8C_MINI_RESULT b = 1, scheduled like any command: every device applies it at one frame)
void miniDecide(const Rm8MiniWaitInfo &mi, const char *why)
{
	if(S.miniDecided == mi.serial) return;
	S.miniDecided = mi.serial;
	Rm8NetCommand c; c.kind = RM8C_MINI_RESULT; c.seat = 0; c.a = mi.game; c.b = 1; S.pending.push_back(c);
	rm8Log("net: minigame %d of seat %d: the host decides with the computer logic (%s) after %u frames", mi.game, mi.seat, why, mi.frames);
	notice(roleName(mi.seat) + " 的小游戏改由电脑决定结果（" + why + "）", 6);
}
// [N4] 插海盗 with everybody: the host decides the computer's stab of a computer seat (when its own game reaches that turn, as the DLL's 0.7 s pause; or after a
// few seconds), of an absent player at once, and of a player who took too long (the safety net; his own device already sends the computer's choice after
// 7 s); once the referee has the result and every player's device has shown it (DONE, or 15 s), FINAL applies it everywhere at one frame
int miniTurnTimeoutSec(){ static const int t = getenv("RM8_NET_MINI_TURN_TIMEOUT") ? std::max(5, atoi(getenv("RM8_NET_MINI_TURN_TIMEOUT"))) : 30; return t; }
void hostMini21(const Rm8MiniWaitInfo &mi)
{
	if(!mi.finished){
		char key[48]; snprintf(key, sizeof key, "%u,%d", mi.serial, mi.turn);
		if(S.miniActKey == key) return;
		int o = mi.turnHuman ? ownerOf(mi.turnSeat) : -1;
		bool away = mi.turnHuman && (o < 0 || !peerConnected(o));
		float secs = mi.turnFrames * RM8_NET_STEP, first = mi.turn == 0 ? 25.0f : 0.0f;	// the first turn comes after the rules panel and the pirate pick (about 20 s)
		const char *why = nullptr;
		if(!mi.turnHuman){ if(mi.dueTurn == mi.turn || secs > first + 12.0f) why = "computer seat"; }
		else if(away){ if(mi.dueTurn == mi.turn || secs > first + 3.0f) why = "player away"; }
		else if(secs > first + (float)miniTurnTimeoutSec()) why = "player too slow";
		if(!why) return;
		S.miniActKey = key;
		char s[48]; snprintf(s, sizeof s, "%u,%d,0", mi.serial, mi.turn);
		pushHost(RM8C_MINI_ACT, mi.game, RM8M21_AUTO, s);
		rm8Log("net: minigame 21 turn %d (seat %d): the host sends the computer's choice (%s, %.1f s)", mi.turn, mi.turnSeat, why, secs);
		if(mi.turnHuman) notice(roleName(mi.turnSeat) + std::string(away ? " 不在线，这一剑由电脑来插" : " 超时，这一剑由电脑来插"), 4);
		return;
	}
	if(S.miniFinal == mi.serial) return;
	bool all = true;
	std::vector<int> need = {0};	// the host's own game too
	for(int seat : mi.humanSeats){ int o = ownerOf(seat); if(o > 0 && peerConnected(o) && std::find(need.begin(), need.end(), o) == need.end()) need.push_back(o); }
	for(int p : need) if(std::find(mi.donePeers.begin(), mi.donePeers.end(), p) == mi.donePeers.end()) all = false;
	float secs = mi.finishFrames * RM8_NET_STEP;
	if(!all && secs < 15.0f) return;
	S.miniFinal = mi.serial;
	char s[48]; snprintf(s, sizeof s, "%u,%d,0", mi.serial, mi.turn);
	pushHost(RM8C_MINI_ACT, mi.game, RM8M21_FINAL, s);
	rm8Log("net: minigame 21: the result is applied now (%s, %.1f s after the last stab)", all ? "every player's game ended" : "waited long enough", secs);
}
// a base for a peer; the player of the waiting minigame gets it after the host's decision of that minigame (it replays to the decision and never restarts the game)
void baseTo(Peer &p, const char *why = "玩家重新连接")
{
	Rm8MiniWaitInfo mi;
	if(S.inGame && !S.waitPlayers && rm8EventMiniWaiting(&mi) && !mi.group && ownerOf(mi.seat) == p.id){ miniDecide(mi, why); p.baseDue = true; return; }	// (game 21 with everybody: the player replays the actions; his turns are the computer's while he is away)
	sendBase(p);
}

